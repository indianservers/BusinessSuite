import {test,expect} from '../frontend/node_modules/playwright/test';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';

test('live agent project context, receipts, usage and responsive review without another model call',async({page})=>{
  test.skip(process.env.PMS_AGENT_LIVE!=='1','Opt-in: run verify_pms_agent_live.py first. No provider call in this browser test.');
  const root=path.resolve('..'),dir=path.join(root,'docs/qa/suite-operator-2026-10-24');
  const auth=JSON.parse(readFileSync(path.join(root,'.local/operator-live-qa/auth.json'),'utf8'));
  const evidence=JSON.parse(readFileSync(path.join(dir,'pms-agent-live.json'),'utf8'));
  const errors:string[]=[],failed:any[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=400)failed.push({url:r.url(),status:r.status()});});
  await page.addInitScript(a=>sessionStorage.setItem('hrms-auth',JSON.stringify({state:{accessToken:a.token,user:{id:a.user_id,email:'admin@local.invalid',role:'admin',is_superuser:true},isAuthenticated:true},version:0})),auth);
  await page.setViewportSize({width:1500,height:1000});
  await page.goto(`/ai-agents/operator?module=PMS&workspace=${evidence.workspace_id}&project=${evidence.project_id}`);
  await expect(page.getByLabel('Agent project')).toHaveValue(String(evidence.project_id));
  await expect(page.getByRole('checkbox',{name:/Select LA/})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Available actions · PMS'})).toBeVisible();
  await expect(page.getByText('event rule',{exact:true})).toBeVisible();
  await page.getByRole('heading',{name:'Recent requests'}).locator('..').getByRole('button').first().click();
  await expect(page.getByLabel('Suite plan review')).toContainText('succeeded');
  await expect(page.getByLabel('Suite plan review')).toContainText('PMS execution #');
  await page.getByText('PMS impact / step 1',{exact:true}).click();
  await expect(page.getByLabel('Suite plan review')).toContainText('start date');
  await page.getByRole('button',{name:'Usage & request logs',exact:true}).click();
  await expect(page.getByText(/input \/ .*output tokens/).first()).toBeVisible();
  await page.screenshot({path:path.join(dir,'pms-agent-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)).toBe(false);
  await page.screenshot({path:path.join(dir,'pms-agent-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);expect(failed).toEqual([]);
  writeFileSync(path.join(dir,'pms-agent-browser.json'),JSON.stringify({status:'passed',project_id:evidence.project_id,errors,failed},null,2));
});
