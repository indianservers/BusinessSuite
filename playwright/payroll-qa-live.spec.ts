import { test, expect } from '../frontend/node_modules/playwright/test';
import fs from 'node:fs';

test('synthetic employee real API payroll calculation, approval, locking and payslip', async ({ page, request }, info) => {
  const api = process.env.PAYROLL_QA_API || 'http://127.0.0.1:1553/api/v1';
  const login = await request.post(`${api}/auth/login`, { data: { email: 'admin@suiteqa.example.com', password: 'SuiteQA@12345' } });
  expect(login.ok()).toBeTruthy();
  const tokens = await login.json();
  const headers = { Authorization: `Bearer ${tokens.access_token}`, 'X-Suite-Organization': '1', 'X-Suite-Branch': '1' };
  const access = await request.get(`${api}/access/me`, { headers });
  const user = { id: tokens.user_id, email: tokens.email, role: tokens.role, is_superuser: true, access: await access.json() };
  await page.addInitScript(({tokens,user}) => sessionStorage.setItem('hrms-auth', JSON.stringify({state:{accessToken:tokens.access_token,refreshToken:tokens.refresh_token,user,isAuthenticated:true},version:0})), {tokens,user});
  const month = info.project.name === 'desktop' ? 5 : 6;
  const departmentResponse = await request.post(`${api}/company/departments/`,{headers,data:{name:`QA Payroll ${info.project.name}`,branch_id:1}});
  expect(departmentResponse.status(),await departmentResponse.text()).toBe(201);
  const department = await departmentResponse.json();
  const designationResponse = await request.post(`${api}/company/designations/`,{headers,data:{name:`QA Analyst ${info.project.name}`,department_id:department.id}});
  expect(designationResponse.status(),await designationResponse.text()).toBe(201);
  const designation = await designationResponse.json();
  const employeeResponse = await request.post(`${api}/employees/`, { headers, data: { first_name: 'Synthetic', last_name: `Payroll ${info.project.name}`, date_of_joining: '2024-01-01', branch_id: 1, department_id:department.id, designation_id:designation.id, employment_type: 'Full-time', create_user_account: false } });
  expect(employeeResponse.status(), await employeeResponse.text()).toBe(201);
  const employee = await employeeResponse.json();
  const salaryResponse = await request.post(`${api}/payroll/salary`, { headers, data: {employee_id:employee.id,ctc:'360000',basic:'12000',hra:'6000',effective_from:'2024-01-01'} });
  expect(salaryResponse.status(), await salaryResponse.text()).toBe(201);
  const componentsResponse = await request.get(`${api}/payroll/components`,{headers});
  expect(componentsResponse.ok()).toBeTruthy();
  if (!(await componentsResponse.json()).length) {
    const componentResponse = await request.post(`${api}/payroll/components`,{headers,data:{name:'QA Base',code:'QA-BASE',component_type:'Earning',calculation_type:'Fixed',amount:'0'}});
    expect(componentResponse.status(),await componentResponse.text()).toBe(201);
  }
  await page.goto('/hrms/payroll');
  await page.getByRole('button',{name:'Run Payroll',exact:true}).first().click();
  const runCard = page.locator('div').filter({has:page.getByText('Process payroll for a specific month',{exact:true})}).filter({has:page.getByRole('spinbutton')}).last();
  await runCard.getByLabel('Payroll month').selectOption(String(month));
  await runCard.getByRole('spinbutton').fill('2026');
  const firstResponse = page.waitForResponse(r=>r.url().endsWith('/payroll/run') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Run Payroll',exact:true}).last().click();
  const first = await firstResponse;
  let run;
  if (first.status() !== 201) {
    await expect(page.getByRole('button',{name:'Force Run',exact:true})).toBeVisible();
    const forced = page.waitForResponse(r=>r.url().endsWith('/payroll/run') && r.request().method()==='POST');
    await page.getByRole('button',{name:'Force Run',exact:true}).click();
    const response = await forced;
    expect(response.status(),await response.text()).toBe(201);
    run = await response.json();
  } else run = await first.json();
  const recordsResponse = await request.get(`${api}/payroll/runs/${run.id}/records`,{headers});
  expect(recordsResponse.ok()).toBeTruthy();
  const records = await recordsResponse.json();
  expect(run.total_employees).toBe(records.length);
  const record = records.find((r:any)=>r.employee_id===employee.id);
  expect(Number(record.gross_salary)).toBe(30000);
  expect(Number(record.lop_days)).toBe(0);
  const periodName = month === 5 ? 'May 2026' : 'June 2026';
  const tableView=page.getByRole('button',{name:'Table view',exact:true});
  if(await tableView.isVisible()) await tableView.click();
  const expand=page.getByRole('button',{name:'Expand loaded groups',exact:true});
  if(await expand.isVisible()) await expand.click();
  await page.getByText(periodName,{exact:true}).last().click();
  const approval=page.waitForResponse(r=>r.url().endsWith(`/payroll/runs/${run.id}/approve`) && r.request().method()==='PUT');
  await page.getByRole('button',{name:'Force approve',exact:true}).click();
  const approved=await approval;
  expect(approved.status(),await approved.text()).toBe(200);
  await expect(page.getByText('Payroll run approved',{exact:true})).toBeVisible();
  const lockButton=page.getByRole('button',{name:'Lock',exact:true}).first();
  await expect(lockButton).toBeEnabled();
  const locking=page.waitForResponse(r=>r.url().endsWith(`/payroll/runs/${run.id}/approve`) && r.request().method()==='PUT');
  await lockButton.click();
  const locked=await locking;
  expect(locked.status(),await locked.text()).toBe(200);
  await expect(page.getByText('Payroll run locked',{exact:true})).toBeVisible();
  const rejected = await request.post(`${api}/payroll/salary`, {headers,data:{employee_id:employee.id,ctc:'372000',effective_from:`2026-${String(month).padStart(2,'0')}-01`},maxRetries:2});
  expect(rejected.status()).toBe(400);
  const slipResponse = await request.get(`${api}/payroll/payslip?employee_id=${employee.id}&month=${month}&year=2026`,{headers});
  expect(slipResponse.ok(),await slipResponse.text()).toBeTruthy();
  const slip = await slipResponse.json();
  expect(Number(slip.gross_salary)).toBe(30000);
  await page.screenshot({path:`.tmp/payroll-qa-live-${info.project.name}.png`,fullPage:true});
  fs.writeFileSync(`.tmp/payroll-qa-live-${info.project.name}-evidence.json`,JSON.stringify({fixture:'Disposable SQLite, synthetic employee',employee_id:employee.id,run,record,slip,lockedSalaryMutationStatus:rejected.status()},null,2));
});
