async function login(page:Page,index:number){
  await page.route('**/api/**',async route=>{const url=new URL(route.request().url());try{const response=await route.fetch({url:session.api+url.pathname+url.search});await route.fulfill({response});}catch { await route.abort("failed").catch(()=>{}); }});
  const user=session.users[index];
  await page.addInitScript(user=>{sessionStorage.setItem('hrms-auth',JSON.stringify({state:{user,accessToken:user.token,refreshToken:null,isAuthenticated:true},version:0}));localStorage.setItem('hrms-auth',JSON.stringify({state:{user,accessToken:user.token,refreshToken:null,isAuthenticated:true},version:0}));},user);
  await page.goto(`/pms/messages?workspace=${session.workspace}&conversation=${session.conversation}`);
  await expect(page.getByRole('heading',{name:/general/})).toBeVisible({timeout:30000});
}
