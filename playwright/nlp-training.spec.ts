import {test,expect} from '../frontend/node_modules/playwright/test';
test('Excel review and server-only training use two scoped pages',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/nlp-training-qa.html');
 await expect(page.getByRole('heading',{name:'Datasets & user queries',exact:true})).toBeVisible();
 await page.getByLabel('Training Excel file').setInputFiles({name:'commands.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from('fixture input')});
 await page.getByRole('button',{name:'Upload and validate workbook'}).click();
 await expect(page.getByRole('button',{name:'Approve dataset #1'})).toBeDisabled();
 await page.getByLabel('I reviewed all workbook rows, their labels and privacy.').check();
 await page.getByRole('button',{name:'Approve dataset #1'}).click();
 await expect(page.getByRole('button',{name:'Approve dataset #1'})).toBeDisabled();
 const queries=page.getByRole('region',{name:'User query training review'});
 await queries.getByLabel('Query 42 intent').selectOption('leads.list');
 await queries.getByLabel('I checked the label and removed customer, personal and secret information.').check();
 await queries.getByRole('button',{name:'Approve query #42'}).click();
 await expect(queries.getByText('No queries in this filter.',{exact:false})).toBeVisible();
 await page.getByRole('link',{name:'2. Training & models'}).click();
 await expect(page.getByRole('heading',{name:'Training & models',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Start TensorFlow training'})).toBeDisabled();
 await page.getByLabel('My training commands',{exact:false}).check();
 await page.getByRole('button',{name:'Start TensorFlow training'}).click();
 await page.getByRole('button',{name:'Refresh training runs'}).click();
 await expect(page.getByText('Uploaded test: 3/4 correct (raw neural model)')).toBeVisible();
 await page.getByRole('button',{name:'Activate model #9'}).click();
 await expect(page.getByRole('status')).toContainText('Run #9 activated');
 expect(await page.evaluate(()=>(window as any).__nlpQaRequests.some((r:any)=>/bundle\.json|\.keras/.test(r.path)))).toBe(false);
 await page.screenshot({path:'../.local/nlp-template/training-page.png',fullPage:true});
 expect(errors).toEqual([]);
});
