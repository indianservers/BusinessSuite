import { test, expect } from "../frontend/node_modules/playwright/test";

const api = "http://127.0.0.1:8766/api/v1";
test.skip(({ baseURL }) => !["http://127.0.0.1:5181", "http://127.0.0.1:5182"].includes(baseURL || ""), "Requires the disposable PostgreSQL QA server.");

test("owner creates workspace; invited teammate joins, creates a scheduled task; removal blocks access", async ({ page, browser, request }) => {
  const login = await request.post(`${api}/auth/login`, { data: { email: "owner@example.com", password: "WorkspaceQA@123" } });
  expect(login.ok()).toBeTruthy();
  const auth = await login.json();
  await page.addInitScript(({ auth, api }) => {
    window.__AI_HRMS_CONFIG__ = { apiBaseUrl: api };
    localStorage.setItem("hrms-auth", JSON.stringify({ state: { accessToken: auth.access_token, refreshToken: auth.refresh_token, isAuthenticated: true, user: { id: auth.user_id, email: auth.email, role: auth.role, is_superuser: auth.is_superuser } }, version: 0 }));
  }, { auth, api });
  await page.goto("/pms/workspaces");
  const name = `Delivery ${Date.now()}`;
  await page.getByRole("button", { name: "Create workspace", exact: true }).first().click();
  await page.getByLabel("Workspace name", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Create workspace", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  await page.getByRole("button", { name: "Invite people", exact: true }).click();
  await page.getByLabel("Teammate email").fill("member@example.com");
  await page.getByRole("button", { name: "Create invitation", exact: true }).click();
  const link = page.getByLabel("Share invitation link");
  await expect(link).toBeVisible();
  const inviteUrl = await link.inputValue();
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await page.getByRole("button", { name: "Create project", exact: true }).first().click();
  await page.getByLabel("Project name", { exact: true }).fill("Workspace launch");
  await page.getByLabel("Project key", { exact: true }).fill(`W${Date.now().toString().slice(-7)}`);
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const projectResponse = await request.get(`${api}/project-management/projects`, { headers: { Authorization: `Bearer ${auth.access_token}` } });
  const projectId = (await projectResponse.json()).findLast((p: any) => p.name === "Workspace launch").id;

  const teammateContext = await browser.newContext();
  const teammate = await teammateContext.newPage();
  await teammate.addInitScript(api => { window.__AI_HRMS_CONFIG__ = { apiBaseUrl: api }; }, api);
  await teammate.goto(inviteUrl);
  await expect(teammate).toHaveURL(/login\?next=/);
  await teammate.getByLabel("Email address", { exact: true }).fill("member@example.com");
  await teammate.getByLabel("Password", { exact: true }).fill("WorkspaceQA@123");
  await teammate.getByRole("button", { name: /sign in/i }).click();
  await teammate.waitForURL(/\/pms\/workspaces\?invite=/);
  await teammate.getByRole("button", { name: "Accept invitation", exact: true }).click();
  await expect(teammate.getByRole("heading", { level: 1 })).toBeVisible();
  await teammate.getByRole("button", { name: "New task", exact: true }).click();
  await teammate.getByLabel("Title", { exact: true }).fill("Prepare workspace launch");
  await teammate.getByLabel("Task start date").fill("2026-10-22");
  await teammate.getByLabel("Due date", { exact: true }).fill("2026-10-25");
  await teammate.getByLabel("Task assignee").selectOption({ label: "member@example.com" });
  await teammate.getByRole("button", { name: "Create task", exact: true }).click();
  await expect(teammate.getByText("Prepare workspace launch", { exact: true })).toBeVisible();
  await teammate.goto(`/pms/projects/${projectId}/gantt`);
  await expect(teammate.getByText("Prepare workspace launch", { exact: true }).first()).toBeVisible();
  await page.goto("/pms/workspaces");
  await page.getByLabel("Workspace", { exact: true }).selectOption({ label: `${name} · Owner` });
  await page.getByRole("tab", { name: /People/ }).click();
  await expect(page.getByText("member@example.com", { exact: true }).first()).toBeVisible();
  await page.getByLabel("Role for member@example.com").selectOption("Admin");
  await expect(page.getByLabel("Role for member@example.com")).toHaveValue("Admin");
  await page.screenshot({ path: "test-results/pms-workspace-members.png", fullPage: true });
  await page.getByRole("button", { name: "Remove", exact: true }).click();
  await expect(page.getByLabel("Role for member@example.com")).toHaveCount(0);
  await teammate.reload();
  await expect(teammate.getByText(/access denied/i).first()).toBeVisible();
  await teammateContext.close();
});

test("drag task to a status and teammate; comments and list changes persist", async ({ page, request }) => {
  await page.setViewportSize({ width: 1536, height: 1000 });
  const login = await request.post(`${api}/auth/login`, { data: { email: "owner@example.com", password: "WorkspaceQA@123" } });
  const auth = await login.json();
  await page.addInitScript(({ auth, api }) => {
    window.__AI_HRMS_CONFIG__ = { apiBaseUrl: api };
    localStorage.setItem("hrms-auth", JSON.stringify({ state: { accessToken: auth.access_token, refreshToken: auth.refresh_token, isAuthenticated: true, user: { id: auth.user_id, email: auth.email, role: auth.role, is_superuser: auth.is_superuser } }, version: 0 }));
  }, { auth, api });
  await page.goto("/pms/workspaces");
  await page.getByLabel("Workspace", { exact: true }).selectOption({ label: "Product studio · Owner" });
  const title = "Shape the launch story";
  await expect(page.getByRole("button", { name: title, exact: true })).toBeVisible();
  const data = await (await request.get(`${api}/project-management/workspaces/1/overview`, { headers: { Authorization: `Bearer ${auth.access_token}` } })).json();
  const task = data.tasks.find((t: any) => t.title === title);
  async function dragTo(target: import("../frontend/node_modules/playwright/test").Locator, offsetY?: number) {
    const handle = page.getByRole("button", { name: `Drag ${title}`, exact: true });
    const from = await handle.boundingBox(); const to = await target.boundingBox();
    expect(from).toBeTruthy(); expect(to).toBeTruthy();
    await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2);
    await page.mouse.down();
    await page.mouse.move(from!.x + from!.width / 2 + 10, from!.y + from!.height / 2, { steps: 5 });
    await page.mouse.move(to!.x + to!.width / 2, to!.y + (offsetY || to!.height / 2), { steps: 24 });
    await page.mouse.up();
  }
  await dragTo(page.getByRole("region", { name: "In progress column", exact: true }), 20);
  await expect(page.getByRole("region", { name: "In progress column", exact: true }).getByRole("button", { name: title, exact: true })).toBeVisible();
  await dragTo(page.getByTestId(`assign-${auth.user_id}`));
  await page.getByRole("button", { name: title, exact: true }).click();
  await expect(page.getByLabel("Task assignee", { exact: true })).toHaveValue(String(auth.user_id));
  await expect(page.getByLabel("Task status", { exact: true })).toHaveValue("In Progress");
  const comment = `The draft is ready for a team review. ${Date.now()}`;
  await page.getByLabel("Write a comment").fill(comment);
  await page.getByRole("button", { name: "Send comment", exact: true }).click();
  await expect(page.getByText(comment, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Close task", exact: true }).click();
  await page.reload();
  await expect(page.getByRole("region", { name: "In progress column", exact: true }).getByRole("button", { name: title, exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "List", exact: true }).click();
  await expect(page.getByLabel(`Status for ${title}`, { exact: true })).toHaveValue("In Progress");
  await expect(page.getByLabel(`Assignee for ${title}`, { exact: true })).toHaveValue(String(auth.user_id));
  await page.getByLabel(`Status for ${title}`, { exact: true }).selectOption("Done");
  await page.getByRole("tab", { name: "Board", exact: true }).click();
  await expect(page.getByRole("region", { name: "Done column", exact: true }).getByRole("button", { name: title, exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/pms-workspace-board.png", fullPage: true });
  await page.getByRole("tab", { name: /People/ }).click();
  await expect(page.getByRole("heading", { name: /Meet your people/ })).toBeVisible();
  await page.screenshot({ path: "test-results/pms-workspace-people.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: "test-results/pms-workspace-mobile.png", fullPage: true });
  expect((await request.get(`${api}/project-management/tasks/${task.id}`, { headers: { Authorization: `Bearer ${auth.access_token}` } })).ok()).toBeTruthy();
});
