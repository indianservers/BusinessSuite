import { expect, test } from "../frontend/node_modules/playwright/test";
import { authenticateCrm } from "./crm-core-test-utils";

test("CRM shares the notes editor, keeps local drafts and arranges tasks without PMS data", async ({ page }) => {
  await authenticateCrm(page);
  await page.route("**/api/v1/access/**", route => route.fulfill({ status: 200, contentType: "application/json", body: "{}" }));
  const dataCalls: string[] = [];
  page.on("request", request => { if (/\/(project-management\/(notes|tasks)|crm\/(tasks|activities))(?:[/?]|$)/.test(request.url()) && request.url().includes("/api/")) dataCalls.push(request.url()); });
  await page.goto("/crm/activities?operation=%2Fcrm%2Ftasks");
  const workspace = page.getByRole("region", { name: "Tasks and notes workspace" });
  await expect(workspace.getByRole("heading", { name: "Tasks & notes" })).toBeVisible();
  await workspace.getByRole("button", { name: "New task", exact: true }).first().click();
  const composer = page.getByRole("region", { name: "CRM task creation" });
  await expect(composer.getByRole("heading", { name: "1. Basic Info" })).toBeVisible();
  await composer.getByRole("textbox", { name: "Task Title", exact: true }).fill("Prepare proposal");
  await composer.getByRole("combobox", { name: "Task status", exact: true }).selectOption("In Progress");
  await composer.getByRole("button", { name: "Create Task", exact: true }).first().click();
  await workspace.getByRole("button", { name: "Arrange", exact: true }).click();
  await expect(workspace.getByText("Prepare proposal", { exact: true })).toBeVisible();
  await workspace.getByRole("combobox", { name: "Move Prepare proposal to", exact: true }).selectOption("Done");
  await expect(workspace.getByRole("region", { name: "Done", exact: true }).getByText("Prepare proposal", { exact: true })).toBeVisible();
  const handle = await workspace.getByRole("button", { name: "Move Prepare proposal", exact: true }).boundingBox();
  const lane = await workspace.getByRole("region", { name: "To Do", exact: true }).boundingBox();
  if (!handle || !lane) throw new Error("Board drag targets missing");
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2 + 10, handle.y + handle.height / 2, { steps: 3 });
  await page.mouse.move(lane.x + lane.width / 2, lane.y + lane.height / 2, { steps: 20 });
  await page.mouse.up();
  await expect(workspace.getByRole("region", { name: "To Do", exact: true }).getByText("Prepare proposal", { exact: true })).toBeVisible();
  await workspace.getByRole("button", { name: "Notes", exact: true }).click();
  await workspace.getByRole("button", { name: "New note", exact: true }).first().click();
  await workspace.getByRole("textbox", { name: "Note title", exact: true }).fill("Discovery notes");
  await workspace.getByRole("textbox", { name: "Note content", exact: true }).fill("Customer priorities");
  await workspace.getByRole("button", { name: "Add notebook", exact: true }).click();
  await workspace.getByRole("textbox", { name: "Notebook name" }).fill("Sales ideas");
  await workspace.getByRole("button", { name: "Add", exact: true }).click();
  await workspace.getByRole("button", { name: "All notes", exact: false }).click();
  await workspace.getByRole("button", { name: /Discovery notes/ }).dragTo(workspace.getByRole("button", { name: /^Sales ideas/ }));
  await expect(workspace.getByRole("combobox", { name: "Move to notebook" })).toHaveValue(/.+/);
  await expect(workspace.getByRole("combobox", { name: "Move to notebook" }).locator("option:checked")).toHaveText("Sales ideas");
  await page.reload();
  await workspace.getByRole("button", { name: /Discovery notes/ }).click();
  await expect(workspace.getByRole("textbox", { name: "Note content", exact: true })).toContainText("Customer priorities");
  await workspace.getByRole("button", { name: "Delete selected item" }).click();
  await workspace.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(workspace.getByRole("button", { name: /Discovery notes/ })).toBeVisible();
  expect(dataCalls).toEqual([]);
  await workspace.getByRole("button", { name: /Discovery notes/ }).click();
  await page.screenshot({ path: "test-results/crm-productivity-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => (await workspace.boundingBox())?.x ?? 999).toBeLessThan(30);
  await expect(workspace.getByRole("textbox", { name: "Note title", exact: true })).toBeVisible();
  await expect(workspace.getByRole("button", { name: "Back", exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/crm-productivity-mobile.png", fullPage: true });
});

test("PMS-style CRM creation restores drafts and keeps data local", async ({ page }) => {
  await authenticateCrm(page);
  await page.route("**/api/v1/access/**", route => route.fulfill({ status: 200, contentType: "application/json", body: "{}" }));
  const dataCalls: string[] = [];
  page.on("request", r => { if (r.url().includes("/api/v1/project-management/") || (r.url().includes("/api/v1/crm/") && r.method() !== "GET")) dataCalls.push(r.url()); });
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/crm/activities?operation=%2Fcrm%2Ftasks");
  const workspace = page.getByRole("region", { name: "Tasks and notes workspace" });
  const form = page.getByRole("region", { name: "CRM task creation" });
  await workspace.getByRole("button", { name: "New task", exact: true }).first().click();
  await expect(form.getByRole("heading", { name: "Assignment Summary" })).toBeVisible();
  await form.getByRole("textbox", { name: "Task Title", exact: true }).fill("Follow up on renewal");
  await form.getByRole("button", { name: /Use template/ }).click();
  await form.getByLabel("Select assignees", { exact: true }).fill("Sales owner");
  await form.getByRole("button", { name: "Add", exact: true }).click();
  await form.getByRole("combobox", { name: "Priority", exact: true }).selectOption("High");
  await form.getByRole("textbox", { name: "Subtasks", exact: true }).fill("Prepare renewal brief");
  await form.getByRole("button", { name: "Add subtask", exact: true }).click();
  await form.getByRole("button", { name: "Save Draft", exact: true }).click();
  await form.getByRole("heading", { name: "Create Task", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/crm-task-creation-desktop.png", fullPage: true });
  await page.reload();
  await workspace.getByRole("button", { name: "New task", exact: true }).first().click();
  await form.getByRole("button", { name: "Restore draft", exact: true }).click();
  await expect(form.getByRole("textbox", { name: "Task Title", exact: true })).toHaveValue("Follow up on renewal");
  await expect(form.getByText("1 assignees selected", { exact: true })).toBeVisible();
  await expect(form.getByText("Prepare renewal brief", { exact: true })).toBeVisible();
  await form.getByRole("combobox", { name: "Task location", exact: true }).selectOption("Deal task");
  await form.getByRole("textbox", { name: "Related CRM record", exact: true }).fill("Renewal opportunity");
  await form.getByRole("checkbox", { name: "Create another" }).check();
  await form.getByRole("button", { name: "Create Task", exact: true }).first().click();
  await expect(form.getByRole("textbox", { name: "Task Title", exact: true })).toHaveValue("");
  await form.getByRole("button", { name: /Copy from existing/ }).click();
  await form.getByRole("combobox", { name: "Copy a local task" }).selectOption({ label: "Follow up on renewal" });
  await expect(form.getByRole("textbox", { name: "Task Title", exact: true })).toHaveValue("Follow up on renewal (copy)");
  await page.setViewportSize({ width: 390, height: 844 });
  await form.getByRole("heading", { name: "Create Task", exact: true }).scrollIntoViewIfNeeded();
  await expect.poll(async () => (await form.boundingBox())?.x ?? 999).toBeLessThan(30);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: "test-results/crm-task-creation-mobile.png", fullPage: true });
  expect(dataCalls).toEqual([]);
});
