import { test, expect } from '../frontend/node_modules/playwright/test';
import { readFile } from 'node:fs/promises';

test('live local action: review, execute, receipt, memory and mobile', async ({ page }) => {
  const errors:string[]=[];
  page.on('pageerror', error => errors.push(error.message));
  const login = await page.request.post('/api/v1/auth/login', { data: { email:'admin@suiteqa.example.com', password:'SuiteQA@12345' } });
  expect(login.ok()).toBe(true);
  const auth = await login.json();
  const me = await page.request.get('/api/v1/auth/me', { headers: { Authorization:`Bearer ${auth.access_token}` } });
  expect(me.ok()).toBe(true);
  expect((await me.json()).email).toBe('admin@suiteqa.example.com');
  const user={id:auth.user_id,email:auth.email,role:auth.role,is_superuser:auth.is_superuser,employee_id:auth.employee_id};
  await page.goto('/login');
  await page.evaluate(async ({ auth, user }) => {
    const { useAuthStore } = await import('/src/store/authStore.ts');
    sessionStorage.setItem('suite-organization','1');
    sessionStorage.setItem('suite-branch','1');
    useAuthStore.setState({ accessToken:auth.access_token, refreshToken:auth.refresh_token, user, isAuthenticated:true, isHydrated:true });
  }, { auth, user });
  await page.goto('/ai-agents/operator?module=CRM');
  await expect(page.getByRole('heading',{name:'Ask. Review. Get work done.'})).toBeVisible();
  const stamp=Date.now();
  const command=page.getByLabel('Suite command');
  await command.fill(`CRM: Create task called Browser QA ${stamp}`);
  const prepared=page.waitForResponse(response=>response.url().endsWith('/suite/commands')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Send',exact:true}).click();
  const run=await (await prepared).json();
  expect(run.status).toBe('awaiting_approval');
  const review=page.getByLabel('Suite plan review');
  await expect(review).toContainText('awaiting approval');
  await expect(review).toContainText(`Browser QA ${stamp}`);
  await page.getByRole('button',{name:'Approve these exact actions',exact:true}).click();
  await expect(review).toContainText('succeeded');
  await expect(review).toContainText('saved record #');
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download execution receipt'}).click();
  const file=await download;
  expect(file.suggestedFilename()).toBe(`action-agent-receipt-${run.id}.json`);
  const receipt=JSON.parse(await readFile((await file.path())!,'utf8'));
  expect(receipt).toMatchObject({id:run.id,status:'succeeded',version:'action-agent-receipt-v1'});
  expect(receipt.receipts).toHaveLength(1);
  expect(receipt.command).toBeUndefined();expect(receipt.plan).toBeUndefined();
  const history=page.getByLabel('Request history');
  await history.getByLabel('Search request history').fill(`Browser QA ${stamp}`);
  await history.getByLabel('Request status filter').selectOption('succeeded');
  await expect(history.getByRole('button').filter({hasText:`#${run.id} · succeeded`})).toHaveCount(1);
  await page.getByLabel('Module memory text').fill(`Browser preference ${stamp}`);
  await page.getByRole('button',{name:'Save memory',exact:true}).click();
  const memory=page.getByText(`Browser preference ${stamp}`,{exact:true});
  await expect(memory).toBeVisible();
  await memory.locator('..').getByRole('button',{name:'Forget memory',exact:true}).click();
  await expect(memory).toHaveCount(0);
  await page.locator('#suite-main').evaluate(element=>{element.scrollTop=0;});
  await page.screenshot({path:'../outputs/action-agent-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(async()=>Math.round((await page.getByTestId('suite-operator').boundingBox())!.x)).toBeLessThan(24);
  await expect.poll(()=>page.locator('#suite-main').evaluate(element=>getComputedStyle(element).opacity)).toBe('1');
  await page.getByRole('heading',{name:'Ask. Review. Get work done.'}).scrollIntoViewIfNeeded();
  await expect(command).toBeVisible();
  const actions=page.getByRole('button',{name:'New conversation',exact:true});
  await expect(actions).toBeInViewport();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)).toBe(false);
  await page.screenshot({path:'../outputs/action-agent-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
