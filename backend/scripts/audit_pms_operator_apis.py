"""Generate a source-only API inventory for the PMS operator design (stdlib only)."""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PMS = ROOT / 'backend/app/apps/project_management'
MAIN = PMS / 'api/router.py'


def inventory():
    tree = ast.parse(MAIN.read_text(encoding='utf-8-sig'))
    # Only sibling routers imported and included by the PMS root router.
    imported = {}
    included = set()
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.level == 2:
            for name in node.names:
                if name.name == 'router':
                    imported[name.asname or name.name] = node.module
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            call = node.value
            if isinstance(call.func, ast.Attribute) and call.func.attr == 'include_router' and call.args and isinstance(call.args[0], ast.Name):
                included.add(call.args[0].id)
    files = [('PMS', MAIN, '/project-management')]
    files += [('PMS', PMS / f'{module}.py', '/project-management') for alias, module in imported.items() if alias in included]
    files += [
        ('AI operator', ROOT / 'backend/app/ai_operator/api.py', '/ai-operator'),
        ('AI operator', ROOT / 'backend/app/ai_operator/extensions.py', '/ai-operator'),
        ('AI agents', ROOT / 'backend/app/ai_agents/api.py', '/ai-agents'),
        ('AI copilot', ROOT / 'backend/app/apps/ai_copilot/api/router.py', '/ai'),
        ('Adjacent scheduling', ROOT / 'backend/app/apps/scheduling/router.py', '/scheduling'),
    ]
    rows = []
    for group, file, prefix in files:
        source = file.read_text(encoding='utf-8-sig')
        for node in ast.parse(source).body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                    continue
                if not isinstance(decorator.func.value, ast.Name) or decorator.func.value.id != 'router':
                    continue
                method = decorator.func.attr
                if method not in {'get', 'post', 'put', 'patch', 'delete', 'websocket'}:
                    continue
                path = ast.literal_eval(decorator.args[0])
                params = []
                args = node.args.posonlyargs + node.args.args + node.args.kwonlyargs
                for arg in args:
                    if arg.arg not in {'db', 'current_user', 'user', 'request', 'websocket'}:
                        params.append(f'{arg.arg}: {ast.unparse(arg.annotation) if arg.annotation else "untyped"}')
                rows.append({'group': group, 'method': method.upper(), 'path': '/api/v1' + prefix + path,
                             'source': file.relative_to(ROOT).as_posix(), 'line': decorator.lineno,
                             'handler': node.name, 'parameters': params})
    return rows


if __name__ == '__main__':
    rows = inventory()
    assert len({(r['method'], r['path']) for r in rows}) == len(rows), 'Duplicate method/path in inventory'
    docs = ROOT / 'docs'
    (docs / 'PMS_AI_OPERATOR_API_INVENTORY.json').write_text(json.dumps({
        'review_date': '2026-10-24', 'scope': 'Source-declared routes; not live OpenAPI or runtime verification',
        'base_path': '/api/v1 (default API_V1_STR; deployments may override)',
        'route_count': len(rows), 'routes': rows}, indent=2), encoding='utf-8')
    lines = ['# Current PMS and AI API inventory', '', 'Source snapshot: 24 October 2026. Generated by `backend/scripts/audit_pms_operator_apis.py`.', '',
             'These are current source-declared routes, not proposed APIs and not proof of live deployment. Default prefix is `/api/v1`; configuration or module enablement may change availability. Included PMS sibling routers are resolved from the root router imports and include calls. Adjacent scheduling is listed separately and currently targets other BusinessSuite modules, not PMS.', '',
             'Parameter annotations identify handler inputs only; inspect the named Pydantic schemas and handler for defaults, constraints, authorization, response shape, and side effects. Existing HTTP APIs are not automatically available to agents. See the updated audit for tool coverage and proposed additions.', '']
    for group in dict.fromkeys(r['group'] for r in rows):
        group_rows = [r for r in rows if r['group'] == group]
        lines += [f'## {group} — {len(group_rows)} routes', '']
        for source in dict.fromkeys(r['source'] for r in group_rows):
            lines += [f'### {source}', '']
            for r in group_rows:
                if r['source'] == source:
                    lines += [f'- `{r["method"]} {r["path"]}` — `{r["handler"]}` (line {r["line"]}). Inputs: ' + (', '.join(f'`{p}`' for p in r['parameters']) or 'no additional handler parameters') + '.']
            lines += ['']
    (docs / 'PMS_AI_OPERATOR_API_INVENTORY.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({'total': len(rows), 'by_group': {g: sum(r['group'] == g for r in rows) for g in dict.fromkeys(r['group'] for r in rows)}}))
