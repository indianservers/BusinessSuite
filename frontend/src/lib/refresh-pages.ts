export function isRefreshablePage(pathname: string) {
  const path = pathname.replace(/\/$/, "");
  if (/\/(?:new|create|add|edit|builder|designer|settings|profile|preferences|login|notes|docs)(?:\/|$)/.test(path)) return false;
  if (["/srm/pos", "/srm/pos/terminal"].includes(path)) return false;
  return refreshPages.some(page => {
    const segments = page.path.split("/");
    const actual = path.split("/");
    return segments.length === actual.length && segments.every((part, index) => part.startsWith(":") ? Boolean(actual[index]) : part === actual[index]);
  });
}
