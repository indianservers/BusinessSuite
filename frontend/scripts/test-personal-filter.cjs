const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const exported = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/shared/data-grid/personal-filter.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:exported});
const {personalQuery,personalRows}=exported;
const query={search:'client',filters:{logic:'and',rules:[{field:'status',operator:'equals',value:'Open'}]},sorting:[{id:'amount',desc:true}],grouping:['stage'],path:[],page:2,pageSize:25};
const rows=[{id:'1'},{id:'2'},{id:'3'}], getId=row=>row.id;
assert.equal(personalQuery(query,undefined),query);
assert.equal(personalRows(rows,undefined,getId),rows);
const favorites={kind:'favorites',ids:['3','not-accessible']};
const restricted=personalQuery(query,favorites);
assert.deepEqual(Array.from(restricted.recordIds),favorites.ids);
assert.equal(restricted.recordOrder,false);
assert.equal(restricted.filters,query.filters);
assert.equal(restricted.sorting,query.sorting);
assert.equal(restricted.search,'client');
assert.equal(restricted.pageSize,25);
assert.deepEqual(personalRows(rows,favorites,getId).map(getId),['3']);
assert.equal(personalRows(rows,{kind:'favorites',ids:[]},getId).length,0);
assert.equal(personalQuery(query,{kind:'favorites',ids:[]}).recordIds.length,0);
const frequent={kind:'frequent',ids:['3','1']};
assert.deepEqual(personalRows(rows,frequent,getId).map(getId),['3','1']);
assert.equal(personalQuery(query,frequent).recordOrder,true);
assert.equal(personalQuery(query,frequent).sorting.length,0);
assert.equal(personalQuery(query,frequent,'key').recordIdentity,'key');
assert.deepEqual(rows.map(getId),['1','2','3']);
assert.deepEqual(query.sorting,[{id:'amount',desc:true}]);
assert.equal(query.recordIds,undefined);
assert.equal(personalQuery(query,{kind:null}),query);
console.log('Personal subsets: empty vs all, permitted-row intersection, frequent order, query preservation and no input mutation passed.');
