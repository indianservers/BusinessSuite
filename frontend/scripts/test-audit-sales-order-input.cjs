const assert=require('node:assert/strict');
const path=require('node:path');
const {buildSync}=require('esbuild');
const result=buildSync({entryPoints:[path.resolve(__dirname,'../src/apps/srm/sales-order-input.ts')],bundle:true,write:false,platform:'node',format:'cjs'});
const mod={exports:{}};new Function('module','exports',result.outputFiles[0].text)(mod,mod.exports);
const {salesOrderInput}=mod.exports;
const order={title:'QA_TEST_2026_SO_001',customer_id:'73',currency:'INR',expected_start_date:'2026-11-13',expected_end_date:'2026-11-20',terms:''};
const product={item_id:4,kind:'product',name:'Audit product',quantity:2,unit_price:250,discount:10,currency:'INR',tax_rate:18};
const service={item_id:5,kind:'service',name:'Audit service',quantity:1,unit_price:100,discount:0,currency:'INR',tax_rate:5};
const body=salesOrderInput(order,[product,service]);
assert.equal(body.title,order.title);assert.equal(body.customer_id,73);
assert.deepEqual([body.subtotal,body.discount_amount,body.tax_amount,body.total_amount],[600,50,86,636]);
assert.equal(body.lines[1].service_type,'service');assert.equal(body.lines[0].product_id,4);
assert.equal(salesOrderInput(order,[{...product,quantity:1,unit_price:0.05,tax_rate:0}]).total_amount,0.04);
for(const value of ['', 'QA_TEST_CUSTOMER', '0','-1','1.5'])assert.throws(()=>salesOrderInput({...order,customer_id:value},[product]),/Choose a customer/);
assert.throws(()=>salesOrderInput(order,[]),/at least one/);
for(const patch of [{quantity:NaN},{quantity:0},{quantity:-1},{unit_price:-1},{unit_price:Infinity},{discount:101},{tax_rate:-1},{currency:'USD'}])assert.throws(()=>salesOrderInput(order,[{...product,...patch}]));
assert.throws(()=>salesOrderInput({...order,expected_end_date:'2026-01-01'},[product]),/Start date/);
console.log('PASS sales order input: references, multiple lines, products/services, discounts/tax/totals, malformed values, dates, title preservation');
