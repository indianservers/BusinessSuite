const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const directory = path.resolve(__dirname, '../src/shared/workflow-board');
function compile(name, imports = {}) {
  const source = fs.readFileSync(path.join(directory, name + '.ts'), 'utf8');
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const result = { exports: {} };
  vm.runInNewContext(code, { exports: result.exports, require: id => { assert(id in imports, id); return imports[id]; }, Date, Intl, Map, Set, Number, String, Object, Array });
  return result.exports;
}
