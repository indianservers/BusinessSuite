const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/apps/communication/center/time.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const sandbox = { exports: {}, Intl, Date, Error };
vm.runInNewContext(compiled, sandbox);
const { zonedInstant, localDateKey } = sandbox.exports;
assert.equal(zonedInstant('2026-11-03T09:00', 'Asia/Kolkata'), '2026-11-03T03:30:00.000Z');
assert.equal(zonedInstant('2026-11-03T09:00', 'America/New_York'), '2026-11-03T14:00:00.000Z');
assert.equal(zonedInstant('2026-07-03T09:00', 'Europe/London'), '2026-07-03T08:00:00.000Z');
assert.equal(zonedInstant('2026-11-03T09:00', 'UTC'), '2026-11-03T09:00:00.000Z');
assert.throws(() => zonedInstant('2026-03-08T02:30', 'America/New_York'));
assert.throws(() => zonedInstant('2026-02-30T09:00', 'UTC'));
assert.throws(() => zonedInstant('not-a-date', 'UTC'));
assert.equal(localDateKey(new Date(2026,10,3,0,5).toISOString()), '2026-11-03');
assert.equal(localDateKey(new Date(2026,10,3,23,59).toISOString()), '2026-11-03');
console.log('9 communication schedule and calendar timezone checks passed');
