const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/apps/crm/integrationFeedback.ts'), 'utf8');
const result = {};
vm.runInNewContext(ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:result, URL, URLSearchParams});
const { integrationError, webhookValidation } = result;
assert.equal(integrationError({response:{data:{detail:[{msg:'Endpoint is required'},{loc:['body']},{msg:'Choose an event'}]}}}, 'fallback'), 'Endpoint is required. Choose an event');
assert.equal(integrationError({response:{data:{detail:'Provider is not configured'}}}, 'fallback'), 'Provider is not configured');
assert.equal(integrationError(null, 'Retry status'), 'Retry status');
assert.equal(integrationError({response:{data:{detail:{bad:true}}}}, 'fallback'), 'fallback');
const draft = {name:'CRM hook', url:'https://example.com/hook', events:['lead.created']};
assert.equal(webhookValidation(draft), undefined);
assert.match(webhookValidation({...draft,name:'  '}), /name/);
assert.match(webhookValidation({...draft,url:'invalid'}), /HTTPS/);
assert.equal(webhookValidation({...draft,url:'http://localhost:8000/hook'}), undefined);
assert.match(webhookValidation({...draft,url:'https://secret@example.com'}), /credentials/);
assert.match(webhookValidation({...draft,events:[]}), /event/);
assert.equal(result.calendarReturnSearch('?operation=%2Fcrm%2Fcalendar-integrations&code=one-use&state=nonce&scope=calendar'), '?operation=%2Fcrm%2Fcalendar-integrations&scope=calendar');
assert.equal(result.calendarReturnSearch('?error=access_denied&error_description=denied&state=nonce'), '');
console.log('12 integration validation, callback and recovery checks passed.');
