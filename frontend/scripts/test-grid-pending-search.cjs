const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const code = fs.readFileSync(path.join(__dirname, '../src/shared/data-grid/pendingSearch.ts'), 'utf8');
const exported = {};
vm.runInNewContext(ts.transpileModule(code, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:exported});
const compose = exported.mergePendingGridSearch;
const current = {search:'January',page:2,pageSize:50,sort:'date'};
let next = compose(current, {...current,pageSize:10,page:1}, '');
assert.equal(next.search,''); assert.equal(next.pageSize,10); assert.equal(next.page,1);
next = compose(current, {...current,sort:'amount'}, 'February');
assert.equal(next.search,'February'); assert.equal(next.sort,'amount'); assert.equal(next.page,1);
assert.equal(compose(current,{...current,page:3},'January').page,3);
next = compose(current,{search:'Saved view',page:1,pageSize:25,sort:'owner'},'',true);
assert.equal(next.search,'Saved view'); assert.equal(next.pageSize,25);
assert.equal(compose(current,{...current,search:'',page:1},'Typing',true).search,'');
assert.equal(current.search,'January'); assert.equal(current.page,2);
console.log('12 pending-search composition, paging and explicit-reset assertions passed.');
