const assert = require('node:assert/strict');
const path = require('node:path');
const { buildSync } = require('esbuild');
const source = buildSync({entryPoints: [path.resolve(__dirname, '../src/apps/srm/collection-form-utils.ts')], bundle: true, platform: 'node', format: 'cjs', write: false}).outputFiles[0].text;
const compiled = {exports: {}};
new Function('module', 'exports', source)(compiled, compiled.exports);
const {collectionFormError, localReceiptDate} = compiled.exports;
const error = detail => ({response: {data: {detail}}});
assert.equal(collectionFormError(error([{loc: ['body', 'receipt_date'], msg: 'Invalid date'}]), 'fallback'), 'receipt date: Invalid date');
assert.equal(collectionFormError(error([null, {}, {msg: 'Invalid amount'}]), 'fallback'), 'Invalid amount');
assert.equal(collectionFormError(error({message: 'Invoice closed'}), 'fallback'), 'Invoice closed');
assert.equal(collectionFormError(error('Payment rejected'), 'fallback'), 'Payment rejected');
for (const detail of [null, {}, [], [null], {message: {nested: true}}, '']) assert.equal(collectionFormError(error(detail), 'fallback'), 'fallback');
assert.equal(collectionFormError(null, 'fallback'), 'fallback');
process.env.TZ = 'Asia/Kolkata';
assert.equal(localReceiptDate(new Date('2026-11-16T20:00:00Z')), '2026-11-17');
process.env.TZ = 'America/Los_Angeles';
assert.equal(localReceiptDate(new Date('2026-11-17T02:00:00Z')), '2026-11-16');
console.log('13 SRM collection error and local receipt-date checks passed.');
