const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),ts=require('typescript');
const source=fs.readFileSync(path.join(__dirname,'../src/apps/crm/leads/lead-summary.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const moduleValue={exports:{}};new Function('exports','require','module',output)(moduleValue.exports,require,moduleValue);
const {updateLeadSummary}=moduleValue.exports;
const empty={items:[],total:0,summary:{total:0,active:0,overdue:0,slaBreached:0,stale:0},byStage:{},bySource:{}};
const lead={id:12,status:'New',source:'Referral',signals:{active:true,overdue:false,slaBreached:false,stale:false}};
let current=updateLeadSummary(empty,lead,true);
assert.deepEqual(current.summary,{total:1,active:1,overdue:0,slaBreached:0,stale:0});
assert.deepEqual(current.byStage,{New:1});assert.deepEqual(current.bySource,{Referral:1});
current={...current,items:[lead]};
assert.deepEqual(updateLeadSummary(current,lead,true).summary,current.summary,'replayed create must not double count');
const lost={...lead,status:'Lost',source:'Website',signals:{...lead.signals,active:false}};
const changed=updateLeadSummary(current,lost,false);
assert.equal(changed.summary.total,1);assert.equal(changed.summary.active,0);
assert.deepEqual(changed.byStage,{New:0,Lost:1});assert.deepEqual(changed.bySource,{Referral:0,Website:1});
assert.equal(updateLeadSummary(empty,lost,false),empty,'an unknown edited row cannot establish a summary delta');
assert.equal(empty.summary.total,0,'do not mutate the existing response');
console.log('PASS lead summaries: immediate create/update totals, stage/source transitions, duplicate event and unknown-row guards');
