const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const code = fs.readFileSync(path.join(__dirname,'../src/apps/project-management/pages/workspaceTypes.ts'),'utf8');
const result = {};
vm.runInNewContext(ts.transpileModule(code,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:result,Error});
const error = result.workspaceError;
assert.match(error(new Error('Choose a reviewer and due date for individual assignments.')), /Choose a reviewer/);
assert.equal(error({response:{data:{detail:'This task changed. Reload before saving.'}}}), 'This task changed. Reload before saving.');
assert.equal(error({response:{data:{detail:[{msg:'Title required'},{loc:['body']},{msg:'Date invalid'}]}}}), 'Title required. Date invalid');
assert.match(error({code:'ECONNABORTED'}), /check whether your changes were saved/);
assert.match(error({code:'ERR_NETWORK'}), /Cannot reach the server/);
assert.equal(error(null), 'Something went wrong. Please try again.');
assert.equal(error(undefined), 'Something went wrong. Please try again.');
assert.equal(error({response:{data:{detail:[]}}}), 'Something went wrong. Please try again.');
assert.equal(error(Object.assign(new Error('Request failed with status code 500'),{isAxiosError:true})), 'Something went wrong. Please try again.');
console.log('Workspace errors: 9 validation, recovery and fallback checks passed.');
