const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/shared/workspace/schedule.ts'), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exportsObject = {};
vm.runInNewContext(compiled, {exports:exportsObject, Date, Intl});
const {dayNumber, scheduleRange, scheduleBar} = exportsObject;
assert.equal(dayNumber('2026-02-30'), null, 'Reject rolled-over calendar dates');
assert.equal(dayNumber('invalid'), null);
assert.equal(dayNumber('2026-11-07T23:59:00-08:00'), dayNumber('2026-11-07'), 'Date fields preserve their calendar day');
assert.equal(dayNumber('2026-03-09') - dayNumber('2026-03-08'), 1, 'DST does not shorten a day');
const start = dayNumber('2026-11-01');
assert.equal(scheduleBar({}, start), null, 'Undated records remain unscheduled');
assert.equal(scheduleBar({due:'2026-11-07'}, start).days, 1, 'A single date is a one-day window');
const reversed = scheduleBar({start:'2026-11-10',due:'2026-11-07'}, start);
assert.equal(reversed.reversed, true);
assert.equal(reversed.offset, 6);
assert.equal(reversed.days, 4, 'Invalid date order remains visible for correction');
const range = scheduleRange([{start:'2000-01-01',due:'2040-01-01'}]);
assert.ok(range.days > 3650, 'Long schedules are fitted without clipping later records');
assert.ok(scheduleRange([]).days >= 28);
console.log('Workspace schedule: 11 date, range and visibility checks passed.');
