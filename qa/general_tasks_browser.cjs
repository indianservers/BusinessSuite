// Disposable loopback QA only; never use a deployed service here.
const {chromium, expect: raw} = require("../frontend/node_modules/playwright/test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const expect = raw.configure({timeout: 30000});
(async () => {
  const backend = "http://127.0.0.1:1558/api/v1";
  const login = await (await fetch(backend + "/auth/login", {method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({email:"admin@suiteqa.example.com",password:"SuiteQA@12345"})})).json();
  const headers = {Authorization:"Bearer " + login.access_token,"Content-Type":"application/json"};
  const get = async path => (await fetch(backend + path, {headers})).json();
  const access = await get("/access/me");
  const workspaces = await get("/project-management/workspaces");
  const browser = await chromium.launch({headless:true});
  try {
    const context = await browser.newContext({viewport:{width:1672,height:1100}});
    await context.addInitScript(({login,access}) => sessionStorage.setItem("hrms-auth",JSON.stringify({state:{accessToken:login.access_token,refreshToken:login.refresh_token,isAuthenticated:true,user:{id:login.user_id,email:login.email,role:"admin",is_superuser:true,access}},version:0})),{login,access});
    const page = await context.newPage(); const errors = [];
    page.on("pageerror", e => { errors.push(e.message); console.error(e.message); });
    await page.goto("http://127.0.0.1:5190/pms/people");
    await expect(page.locator(".pd-person-card").first()).toBeVisible();
    await expect(page.locator(".pd-person-card").first().getByRole("button",{name:"Add to workspace",exact:true})).toBeVisible();
    const roles = page.getByRole("combobox").filter({has: page.locator('option[value="superuser"]')});
    assert.equal(await roles.locator('option[value="super_admin"]').count(),0);
    await page.locator(".pd-person-card").first().getByRole("button",{name:"Add to team",exact:true}).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("heading",{name:"Add to team",exact:true})).toBeVisible();
    await dialog.getByRole("radio").first().check();
    await dialog.getByRole("button",{name:"Preview changes",exact:true}).click();
    await expect(dialog.getByRole("button",{name:"Add selected people",exact:true})).toBeEnabled();
    assert.equal(await dialog.getByRole("checkbox").count(),0);
    await dialog.getByRole("button",{name:"Cancel",exact:true}).click();
    await page.goto("http://127.0.0.1:5190/pms/tasks/new");
    await page.getByLabel("Task location",{exact:true}).selectOption("general");
    await page.getByLabel("General task workspace",{exact:true}).selectOption(String(workspaces[0].id));
    const title = "Workspace administration " + Date.now();
    await page.getByLabel("Task Title",{exact:true}).fill(title);
    await expect(page.getByRole("button",{name:"Create Task",exact:true}).first()).toBeEnabled();
    fs.mkdirSync("docs/qa/general-tasks",{recursive:true});
    await page.screenshot({path:"docs/qa/general-tasks/general-task-form.png",fullPage:true});
    await page.getByRole("button",{name:"Create Task",exact:true}).first().click();
    await expect(page.getByRole("heading",{name:"Task Details",exact:true})).toBeVisible();
    await expect(page.getByLabel("Task location",{exact:true})).toHaveValue("general");
    const parentId = Number(new URL(page.url()).pathname.split("/").at(-1));
    const parent = await get(`/project-management/tasks/${parentId}`);
    assert.equal(parent.title,title);
    await page.getByRole("button",{name:"Create subtasks",exact:false}).click();
    await expect(page).toHaveURL(/parentTaskId=/);
    await expect(page.getByLabel("Parent task",{exact:true})).toHaveValue(String(parentId));
    await page.getByLabel("Task Title",{exact:true}).fill("Prepare meeting notes " + Date.now());
    await page.getByRole("button",{name:"Create Task",exact:true}).first().click();
    await expect(page.getByRole("heading",{name:"Task Details",exact:true})).toBeVisible();
    const childId = Number(new URL(page.url()).pathname.split("/").at(-1));
    const child = await get(`/project-management/tasks/${childId}`);
    assert.equal(child.parent_task_id,parentId);
    assert.equal(child.project_id,parent.project_id);
    assert.equal(child.work_type,"Sub-task");
    const projects = await get("/project-management/projects");
    assert.ok(!projects.some(p => p.id === parent.project_id));
    await page.goto("http://127.0.0.1:5190/pms/projects");
    await expect(page.getByRole("link", {name:"Test project MATH",exact:true})).toBeVisible();
    assert.equal(await page.getByRole("link", {name:"General tasks",exact:true}).count(),0);
    assert.deepEqual(errors,[]);
    console.log("PASS: visible workspace action, one admin role, no team confirmation checkbox, general task and subtask created without selecting a project");
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
